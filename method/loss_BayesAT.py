import torch
import torch.nn as nn
import torch.nn.functional as F
from torch.autograd import Variable

from core.metrics import accuracy
from core.trainer import SmoothCrossEntropyLoss
from core.trainer import track_bn_stats


def BayesAT_loss(criterion_mi, model, x_l, y, x_u, optimizer,
               step_size=0.003, epsilon=0.031, perturb_steps=10, lamb=1.0, beta=1.0,
               contrast_label='auto', attack='linf-pgd', label_smoothing=0.1,
               wamodel=None, consistency_cost=0., consistency_prop_label=0.,
               use_soft_labels=False, sample_weights=None, temperature=1.0):  # Added temperature parameter
    device = y.device

    # If using soft labels, y is a probability distribution; otherwise y is class indices
    if use_soft_labels and y.dim() == 2 and y.size(1) > 1:
        # y is soft labels (probability distribution)
        y_soft = y  # Save soft labels
        y_hard = torch.argmax(y, dim=1)  # Convert to hard labels for accuracy calculation, etc.
        num_classes = y.size(1)
        num_y = y.size(0)  # Number of labeled samples
    else:
        # y is hard labels (class indices)
        y_hard = y
        y_soft = None
        num_y = y.size(0)  # Number of labeled samples

    if x_u is None:
        x_natural = x_l
        x_u = torch.empty(0, 0)
    else:
        x_natural = torch.cat([x_l, x_u], dim=0)

    # Initialize loss functions
    criterion_ce = SmoothCrossEntropyLoss(reduction='mean', smoothing=0.0)
    criterion_kl = nn.KLDivLoss(reduction='batchmean')

    model.train()
    track_bn_stats(model, False)
    fea_nat, logits_natural = model(x_natural, feats=True)
    p_natural = F.softmax(logits_natural, dim=1).detach()

    if lamb > 0:
        if contrast_label == 'auto':
            _, pseudo_labels = torch.max(logits_natural, 1)
            labels_4_contrast = pseudo_labels.detach()
            mask = None
        elif contrast_label == 'fixed':
            # For contrastive learning, we still use hard labels
            if use_soft_labels and y_soft is not None:
                # Extract hard labels from soft labels
                labels_4_contrast = torch.argmax(y_soft[:num_y], dim=1).detach()
            else:
                labels_4_contrast = y_hard[:num_y].detach()
            mask = None
        elif contrast_label:
            labels_4_contrast = None
            mask = None

        x_adv = x_natural.detach() + torch.FloatTensor(x_natural.shape).uniform_(-epsilon, epsilon).to(device).detach()
        x_adv = torch.clamp(x_adv, 0.0, 1.0)

        # Generate adversarial examples
        for _ in range(perturb_steps):
            x_adv.requires_grad_()
            with torch.enable_grad():
                fea_adv, logits_adv = model(x_adv, feats=True)
                loss_atk = criterion_kl(F.log_softmax(logits_adv, dim=1), p_natural)
                if beta > 0:
                    # Contrastive loss is not weighted
                    loss_con = criterion_mi(fea_nat, fea_adv, y=labels_4_contrast, mask=mask)
                    loss = loss_atk + beta * loss_con
                else:
                    loss = loss_atk
            grad = torch.autograd.grad(loss, [x_adv])[0]
            x_adv = x_adv.detach() + step_size * torch.sign(grad.detach())
            x_adv = torch.min(torch.max(x_adv, x_natural - epsilon), x_natural + epsilon)
            x_adv = torch.clamp(x_adv, 0.0, 1.0)
        x_adv = Variable(torch.clamp(x_adv, 0.0, 1.0), requires_grad=False)

    model.train()
    track_bn_stats(model, True)
    optimizer.zero_grad()

    fea_nat, logits_natural = model(x_natural, feats=True)

    # ========== Natural loss calculation (using passed sample weights) ==========
    if use_soft_labels and y_soft is not None:
        # Use soft labels: compute KL divergence loss
        log_probs = F.log_softmax(logits_natural[:num_y], dim=1)

        # Apply temperature adjustment: teacher soft labels have already been generated by the teacher model using temperature scaling
        # Student model logits also use the same temperature (optional, here we keep as is)
        # If you want the student to also use temperature, uncomment the following line:
        # log_probs = F.log_softmax(logits_natural[:num_y] / temperature, dim=1)

        # If sample weights are provided, use weighted loss (based on t1 confidence)
        if sample_weights is not None and len(sample_weights) == num_y:
            # Weight the KL divergence for each sample
            kl_per_sample = F.kl_div(log_probs, y_soft[:num_y], reduction='none').sum(dim=1)
            loss_natural_sup = (kl_per_sample * sample_weights[:num_y]).mean()
        else:
            # No weighting, directly compute batchmean
            loss_natural_sup = criterion_kl(log_probs, y_soft[:num_y])
    else:
        # Use hard labels: compute cross-entropy loss
        # If sample weights are provided, use weighted cross-entropy
        if sample_weights is not None and len(sample_weights) == num_y:
            # Compute per-sample cross-entropy
            ce_per_sample = F.cross_entropy(logits_natural[:num_y], y_hard[:num_y], reduction='none')
            loss_natural_sup = (ce_per_sample * sample_weights[:num_y]).mean()
        else:
            loss_natural_sup = criterion_ce(logits_natural[:num_y], y_hard[:num_y])

    if consistency_cost > 0 and x_u.size(0) > 0:
        softmax = torch.nn.Softmax(1)
        num_label_4_consist = int(x_u.size(0) * consistency_prop_label)
        prob_s = softmax(logits_natural[num_y - num_label_4_consist:])
        prob_t = softmax(wamodel(x_natural[num_y - num_label_4_consist:])).detach()
        loss_consistency = consistency_cost * torch.mean((prob_s - prob_t) ** 2, dim=[0, 1])
        loss_natural = loss_natural_sup + loss_consistency
    else:
        loss_natural = loss_natural_sup

    # ========== Robust loss calculation (also uses teacher confidence weights) ==========
    if lamb > 0:
        fea_adv, logits_adv = model(x_adv, feats=True)

        # Robust loss: student predicted natural distribution vs adversarial distribution
        log_probs_adv = F.log_softmax(logits_adv, dim=1)
        probs_natural = F.softmax(logits_natural, dim=1)

        # Compute per-sample KL divergence (for weighting)
        kl_per_sample_robust = F.kl_div(log_probs_adv, probs_natural, reduction='none').sum(dim=1)

        # Use teacher confidence weights for weighting (only for labeled/pseudo-labeled parts)
        if num_y > 0 and sample_weights is not None and len(sample_weights) >= num_y:
            # Use the passed teacher confidence weights
            robust_weights = sample_weights[:num_y]

            # Weighted robust loss (KL divergence part)
            loss_adv_weighted = (kl_per_sample_robust[:num_y] * robust_weights).mean()
        else:
            # If no weights or no labeled data, use ordinary KL loss
            loss_adv_weighted = criterion_kl(log_probs_adv, probs_natural)

        # Contrastive loss
        loss_con = torch.tensor(0)
        # Recommended simplest approach
        if beta > 0:
            # Compute original contrastive loss (scalar)
            loss_con = criterion_mi(fea_nat, fea_adv, y=labels_4_contrast, mask=mask)

            # If sample weights are provided, perform weighting
            if num_y > 0 and sample_weights is not None and len(sample_weights) >= num_y:
                # Use the passed teacher confidence weights (only the part corresponding to x_l)
                robust_weights = sample_weights[:num_y]

                # Compute weighting factor
                # Method A: simple average
                avg_weight = robust_weights.mean()

                # Weight the contrastive loss
                loss_con = loss_con * avg_weight

        loss_robust = loss_adv_weighted + beta * loss_con

        # Accuracy calculation: always use the provided labels (soft labels converted to hard labels or directly hard labels)
        if use_soft_labels and y_soft is not None:
            y_for_acc = torch.argmax(y_soft[:num_y], dim=1)
        else:
            y_for_acc = y_hard[:num_y]

        batch_metrics = {
            'clean_acc': accuracy(y_for_acc, logits_natural[:num_y].detach()),
            'adversarial_acc': accuracy(y_for_acc, logits_adv[:num_y].detach())}
    else:
        loss_robust = torch.tensor(0)

        # Accuracy calculation
        if use_soft_labels and y_soft is not None:
            y_for_acc = torch.argmax(y_soft[:num_y], dim=1)
        else:
            y_for_acc = y_hard[:num_y]

        batch_metrics = {
            'clean_acc': accuracy(y_for_acc, logits_natural[:num_y].detach())}

    loss = loss_natural + lamb * loss_robust
    loss_dict = {
        'loss': loss,
        'nat_loss': loss_natural,
        'rob_loss': loss_robust,
    }

    return loss_dict, batch_metrics